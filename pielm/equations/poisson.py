# ─────────────────────────────────────────────────────────────────────────────
# PDE-оператор для PIELM
#
# ∇²P = f(x,y)
#
# Для нейрона φ_j(x,y) = σ(W[0,j]·x + W[1,j]·y + b[0,j]):
#   ∂²φ_j/∂x² = σ''(z_j) · W[0,j]²
#   ∂²φ_j/∂y² = σ''(z_j) · W[1,j]²
#
# Оператор: L[φ_j] = σ''(z_j) · (W[0,j]² + W[1,j]²)
#
# Входной слой: input_dim = 2, X = (x, y)
# Возвращает матрицу H_f размера (N_train, n_hidden)
# ─────────────────────────────────────────────────────────────────────────────

def pde_operator_poisson(W, b, X, act_name='tanh', act_dict=None):
    """
    Вычисляет матрицу коллокационных уравнений для уравнения Пуассона.

    Параметры
    ----------
    W        : ndarray (2, n_hidden)  — веса входного слоя
    b        : ndarray (1, n_hidden)  — смещения
    X        : ndarray (N, 2)         — коллокационные точки (x, y)
    act_name : str                    — имя функции активации
    act_dict : dict                   — словарь активаций {name: {f, df, ddf}}

    Возвращает
    ----------
    H_f : ndarray (N, n_hidden)
    """
    Z   = X @ W + b                          # (N, n_hidden)
    ddf = act_dict[act_name]['ddf']
    # L[φ_j] = σ''(z_j) · (W[0,j]² + W[1,j]²)
    H_f = ddf(Z) * (W[0, :]**2 + W[1, :]**2)  # (N, n_hidden)
    return H_f


# ─────────────────────────────────────────────────────────────────────────────
# Правая часть уравнения в коллокационных точках
# ─────────────────────────────────────────────────────────────────────────────

def rhs_poisson(X, source_func, source_params):
    """
    Вычисляет f(x,y) в точках X.

    Параметры
    ----------
    X             : ndarray (N, 2)
    source_func   : callable   — f(x, y, **source_params)
    source_params : dict

    Возвращает
    ----------
    rhs : ndarray (N,)
    """
    x = X[:, 0]
    y = X[:, 1]
    return source_func(x, y, **source_params)


# ─────────────────────────────────────────────────────────────────────────────
# Граничные условия (Дирихле P = 0 на ∂Ω)
# ─────────────────────────────────────────────────────────────────────────────

def boundary_conditions_poisson(n_bc=40):
    """
    Генерирует граничные точки и значения P = 0 на ∂Ω = [0,1]².

    Параметры
    ----------
    n_bc : int — число точек на каждой стороне квадрата

    Возвращает
    ----------
    X_b : ndarray (4·n_bc, 2) — граничные точки
    Y_b : ndarray (4·n_bc,)   — P = 0 на границе
    """
    t = np.linspace(0.0, 1.0, n_bc)

    # Нижняя сторона: y = 0
    bottom = np.column_stack([t, np.zeros(n_bc)])
    # Верхняя сторона: y = 1
    top    = np.column_stack([t, np.ones(n_bc)])
    # Левая сторона:  x = 0
    left   = np.column_stack([np.zeros(n_bc), t])
    # Правая сторона: x = 1
    right  = np.column_stack([np.ones(n_bc), t])

    X_b = np.vstack([bottom, top, left, right])    # (4·n_bc, 2)
    Y_b = np.zeros(len(X_b))                       # P = 0
    return X_b, Y_b