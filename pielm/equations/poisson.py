import numpy as np


# ─────────────────────────────────────────────────────────────────────────────
# Уравнение Пуассона (стационарная фильтрация несжимаемой жидкости)
#
# Вывод (Леонтьев §7, формулы 7.1–7.3):
#   div u = 0
#   u = -(k/μ) · grad P
#   → ∇²P = f(x,y)
#
# Область: Ω = [0,1]²
# ГУ Дирихле: P = 0 на ∂Ω
#
# Аналитического решения нет при сложном источнике f(x,y).
# ─────────────────────────────────────────────────────────────────────────────


# ── Варианты источникового члена f(x,y) ──────────────────────────────────────

def source_trigonometric(x, y, A=1.0, B=1.0):
    """
    Тригонометрический источник без аналитического решения:
        f(x,y) = -A·sin(3πx)·exp(y²) - B·cos(πx²)·sin(2πy)

    Параметры
    ----------
    A, B : float — амплитуды составляющих
    """
    return -A * np.sin(3.0 * np.pi * x) * np.exp(y**2) \
           - B * np.cos(np.pi * x**2) * np.sin(2.0 * np.pi * y)


def source_gaussian_multi(x, y, A=1.0, sigma=0.1):
    """
    Несколько гауссовых источников/стоков:
        f(x,y) = A·[exp(-r1²/σ²) - exp(-r2²/σ²) + exp(-r3²/σ²)]
        r1 — расстояние от (0.25, 0.25) — источник
        r2 — расстояние от (0.75, 0.75) — сток
        r3 — расстояние от (0.25, 0.75) — источник

    Параметры
    ----------
    A     : float — амплитуда
    sigma : float — ширина гауссианы
    """
    r1 = (x - 0.25)**2 + (y - 0.25)**2
    r2 = (x - 0.75)**2 + (y - 0.75)**2
    r3 = (x - 0.25)**2 + (y - 0.75)**2
    return A * (
        np.exp(-r1 / sigma**2)
        - np.exp(-r2 / sigma**2)
        + np.exp(-r3 / sigma**2)
    )


def source_combined(x, y, A=1.0, B=0.5, sigma=0.1):
    """
    Комбинированный источник (тригонометрика + гауссиана):
        f(x,y) = -A·sin(2πx)·sin(2πy)
                 + B·exp(-((x-0.5)²+(y-0.5)²)/σ²)

    Параметры
    ----------
    A     : float — амплитуда тригонометрической части
    B     : float — амплитуда гауссовой части
    sigma : float — ширина гауссианы
    """
    trig  = -A * np.sin(2.0 * np.pi * x) * np.sin(2.0 * np.pi * y)
    gauss =  B * np.exp(-((x - 0.5)**2 + (y - 0.5)**2) / sigma**2)
    return trig + gauss


